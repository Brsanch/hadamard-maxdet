def _circulant_rows(generator: Sequence[int]) -> list[list[int]]:
    """Return an m x m circulant whose first row is ``generator``."""
    m = len(generator)
    g = list(generator)
    return [[g[(j - i) % m] for j in range(m)] for i in range(m)]


def two_circulant(a: Sequence[int], b: Sequence[int]) -> Matrix:
    """Construct a two-circulant matrix of order ``n = 2 * len(a)``.

    Block form::

        M = [[ A,    B   ],
             [ B^T, -A^T ]]

    with A, B the m x m circulants generated by ``a`` and ``b``.
    Requires ``len(a) == len(b)`` and all entries in {-1, +1}.

    For ±1 circulants, ``A^T`` is the circulant with first row
    ``(a[0], a[m-1], a[m-2], ..., a[1])``; this routine constructs
    A and B explicitly and transposes in-place so it works uniformly.
    """
    if len(a) != len(b):
        raise ValueError(
            f"two_circulant requires matched generator lengths; got "
            f"{len(a)} and {len(b)}"
        )
    for v in list(a) + list(b):
        if v not in (-1, 1):
            raise ValueError(f"generator entries must be ±1; got {v!r}")

    m = len(a)
    n = 2 * m
    A = _circulant_rows(a)
    B = _circulant_rows(b)
    AT = [[A[j][i] for j in range(m)] for i in range(m)]
    BT = [[B[j][i] for j in range(m)] for i in range(m)]
    nAT = [[-AT[i][j] for j in range(m)] for i in range(m)]

    entries = [[0] * n for _ in range(n)]
    for i in range(m):
        for j in range(m):
            entries[i][j] = A[i][j]
            entries[i][m + j] = B[i][j]
            entries[m + i][j] = BT[i][j]
            entries[m + i][m + j] = nAT[i][j]
    return Matrix(n=n, entries=entries)


def bordered_circulant(core_first_row: Sequence[int]) -> Matrix:
    """Construct a bordered-circulant matrix of order ``n = 1 + len(core)``.

    Shape::

        [ +1   +1  ...  +1 ]
        [ -1                ]
        [ -1     CORE       ]
        [ .                 ]
        [ -1                ]

    where ``CORE`` is the (n-1) x (n-1) circulant whose first row is
    ``core_first_row`` (±1 entries).

    Any ±1 bordered matrix can be brought to this canonical border by
    negating rows/columns, so the ansatz is WLOG up to the |det|-
    preserving sign symmetries. The free parameters are the ``n-1`` bits
    of the core generator.
    """
    for v in core_first_row:
        if v not in (-1, 1):
            raise ValueError(f"core entries must be ±1; got {v!r}")
    m = len(core_first_row)
    n = m + 1
    core = _circulant_rows(core_first_row)

    entries = [[0] * n for _ in range(n)]
    # Border.
    entries[0] = [1] * n
    for i in range(1, n):
        entries[i][0] = -1
        for j in range(1, n):
            entries[i][j] = core[i - 1][j - 1]
    return Matrix(n=n, entries=entries)


def skew_circulant(first_row: Sequence[int]) -> Matrix:
    """Construct a skew-type circulant of order ``n = len(first_row)``.

    A circulant A with first row ``a`` satisfies the ±1 "skew" condition
    ``A + A^T = 2 I`` iff

        a[0] = +1   and   a[i] = -a[n - i]   for 1 <= i < n.

    This requires n odd (otherwise the middle index i = n/2 would force
    a[n/2] = -a[n/2] = 0, violating the ±1 constraint).

    The constructor validates this condition and raises ``ValueError``
    if it does not hold. Free parameters: the (n-1)/2 entries
    ``a[1], a[2], ..., a[(n-1)/2]`` (the rest are determined by the
    skew relation).
    """
    a = list(first_row)
    n = len(a)
    if n == 0:
        raise ValueError("skew_circulant requires a non-empty generator")
    if n % 2 == 0:
        raise ValueError(
            f"skew_circulant requires odd order; got n={n}"
        )
    for v in a:
        if v not in (-1, 1):
            raise ValueError(f"generator entries must be ±1; got {v!r}")
    if a[0] != 1:
        raise ValueError(
            f"skew_circulant requires a[0] = +1 (A + A^T = 2 I); got a[0]={a[0]}"
        )
    for i in range(1, n):
        if a[i] != -a[(n - i) % n]:
            raise ValueError(
                f"skew_circulant requires a[i] = -a[n-i]; violated at i={i} "
                f"(a[{i}]={a[i]}, a[{n - i}]={a[(n - i) % n]})"
            )
    return Matrix.circulant(a)


def skew_generator_from_free_bits(n: int, free_bits: Sequence[int]) -> list[int]:
    """Build a full skew generator of length n from the (n-1)/2 free bits.

    Parameters
    ----------
    n
        Odd order.
    free_bits
        Length ``(n - 1) // 2`` sequence of ±1 values. These fill
        ``a[1], a[2], ..., a[(n-1)/2]``; the remaining entries are set
        by ``a[n - i] = -a[i]``.
    """
    if n % 2 == 0:
        raise ValueError(f"skew generator requires odd n; got {n}")
    half = (n - 1) // 2
    if len(free_bits) != half:
        raise ValueError(
            f"expected {half} free bits for n={n}; got {len(free_bits)}"
        )
    for v in free_bits:
        if v not in (-1, 1):
            raise ValueError(f"free bits must be ±1; got {v!r}")
    a = [0] * n
    a[0] = 1
    for k in range(1, half + 1):
        a[k] = int(free_bits[k - 1])
        a[n - k] = -a[k]
    return a


