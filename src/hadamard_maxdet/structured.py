def _score_abs_det(entries: list[list[int]]) -> int:
    return abs(integer_determinant(entries))


def _log_abs_det(entries: list[list[int]]) -> float:
    d = integer_determinant(entries)
    if d == 0:
        return -math.inf
    return math.log(abs(d))


def _sa_over_bits(
    build_matrix,
    n_bits: int,
    *,
    n_order: int,
    iterations: int,
    t_start: float,
    t_end: float,
    seed: int | None,
    initial_bits: list[int] | None = None,
    log_every: int = 0,
) -> AnnealResult:
    """Generic SA over a ±1 bit vector with pluggable matrix reconstruction.

    ``build_matrix(bits) -> list[list[int]]`` maps a length-``n_bits``
    ±1 vector to a full n x n ±1 matrix. Proposals flip one bit and
    reconstruct the matrix.
    """
    rng = random.Random(seed)
    if initial_bits is None:
        bits = [1 if rng.random() < 0.5 else -1 for _ in range(n_bits)]
    else:
        if len(initial_bits) != n_bits:
            raise ValueError(
                f"initial_bits has length {len(initial_bits)}, expected {n_bits}"
            )
        bits = list(initial_bits)

    current_entries = build_matrix(bits)
    current_e = -_log_abs_det(current_entries)
    # If the initial draw is singular, try a few times to avoid starting at -inf.
    tries = 0
    while current_e == math.inf and tries < 8:
        bits = [1 if rng.random() < 0.5 else -1 for _ in range(n_bits)]
        current_entries = build_matrix(bits)
        current_e = -_log_abs_det(current_entries)
        tries += 1

    best_bits = list(bits)
    best_entries = [row[:] for row in current_entries]
    best_e = current_e

    accepted = 0
    history: list[int] = []
    start = time.monotonic()
    log_ratio = math.log(t_end / t_start) if t_start > 0 else 0.0

    for step in range(iterations):
        frac = step / max(1, iterations - 1)
        t = t_start * math.exp(log_ratio * frac)

        k = rng.randrange(n_bits)
        bits[k] = -bits[k]
        proposal = build_matrix(bits)
        proposal_e = -_log_abs_det(proposal)

        if proposal_e == math.inf:
            # Singular proposal — revert.
            bits[k] = -bits[k]
        else:
            delta = proposal_e - current_e
            if delta <= 0 or rng.random() < math.exp(-delta / max(t, 1e-12)):
                current_entries = proposal
                current_e = proposal_e
                accepted += 1
                if current_e < best_e:
                    best_e = current_e
                    best_entries = [row[:] for row in current_entries]
                    best_bits = list(bits)
            else:
                # Reject: undo flip.
                bits[k] = -bits[k]

        if log_every and step % log_every == 0 and best_e != math.inf:
            history.append(int(round(math.exp(-best_e))))

    walltime = time.monotonic() - start
    best_abs = abs(integer_determinant(best_entries))
    return AnnealResult(
        matrix=Matrix(n=n_order, entries=best_entries),
        abs_det=best_abs,
        iterations=iterations,
        accepted=accepted,
        walltime_seconds=walltime,
        history=history,
    )


def sa_two_circulant(
    n: int,
    *,
    iterations: int = 100_000,
    t_start: float = 1.0,
    t_end: float = 0.01,
    seed: int | None = None,
    initial_a: Sequence[int] | None = None,
    initial_b: Sequence[int] | None = None,
    log_every: int = 0,
) -> AnnealResult:
    """SA over the 2*m ±1 generator bits of a two-circulant of order ``n = 2m``.

    Proposals flip a single bit of the concatenated generator ``[a | b]``
    and rebuild the block matrix.
    """
    if n % 2 != 0:
        raise ValueError(
            f"two-circulant ansatz requires even n; got n={n}"
        )
    m = n // 2
    initial_bits: list[int] | None = None
    if initial_a is not None or initial_b is not None:
        if initial_a is None or initial_b is None:
            raise ValueError(
                "must supply both initial_a and initial_b, or neither"
            )
        if len(initial_a) != m or len(initial_b) != m:
            raise ValueError(
                f"initial generators must each have length m={m}"
            )
        initial_bits = list(initial_a) + list(initial_b)

    def build(bits: list[int]) -> list[list[int]]:
        a = bits[:m]
        b = bits[m:]
        return two_circulant(a, b).entries

    return _sa_over_bits(
        build,
        2 * m,
        n_order=n,
        iterations=iterations,
        t_start=t_start,
        t_end=t_end,
        seed=seed,
        initial_bits=initial_bits,
        log_every=log_every,
    )


def sa_bordered_circulant(
    n: int,
    *,
    iterations: int = 100_000,
    t_start: float = 1.0,
    t_end: float = 0.01,
    seed: int | None = None,
    initial_core: Sequence[int] | None = None,
    log_every: int = 0,
) -> AnnealResult:
    """SA over the n-1 ±1 core bits of a bordered circulant of order ``n``."""
    if n < 2:
        raise ValueError(f"bordered-circulant ansatz requires n >= 2; got {n}")
    m = n - 1
    initial_bits: list[int] | None = None
    if initial_core is not None:
        if len(initial_core) != m:
            raise ValueError(
                f"initial_core must have length n-1={m}; got {len(initial_core)}"
            )
        initial_bits = list(initial_core)

    def build(bits: list[int]) -> list[list[int]]:
        return bordered_circulant(bits).entries

    return _sa_over_bits(
        build,
        m,
        n_order=n,
        iterations=iterations,
        t_start=t_start,
        t_end=t_end,
        seed=seed,
        initial_bits=initial_bits,
        log_every=log_every,
    )


def sa_skew_circulant(
    n: int,
    *,
    iterations: int = 100_000,
    t_start: float = 1.0,
    t_end: float = 0.01,
    seed: int | None = None,
    initial_free_bits: Sequence[int] | None = None,
    log_every: int = 0,
) -> AnnealResult:
    """SA over the (n-1)/2 free bits of a skew-type circulant of odd order ``n``."""
    if n % 2 == 0:
        raise ValueError(f"skew-circulant ansatz requires odd n; got n={n}")
    half = (n - 1) // 2
    initial_bits: list[int] | None = None
    if initial_free_bits is not None:
        if len(initial_free_bits) != half:
            raise ValueError(
                f"initial_free_bits must have length (n-1)/2={half}; got "
                f"{len(initial_free_bits)}"
            )
        initial_bits = list(initial_free_bits)

    def build(bits: list[int]) -> list[list[int]]:
        gen = skew_generator_from_free_bits(n, bits)
        return Matrix.circulant(gen).entries

    return _sa_over_bits(
        build,
        half,
        n_order=n,
        iterations=iterations,
        t_start=t_start,
        t_end=t_end,
        seed=seed,
        initial_bits=initial_bits,
        log_every=log_every,
    )


def multi_start_structured(
    search_fn,
    *,
    n_starts: int = 4,
    base_seed: int = 0,
    **kwargs,
) -> AnnealResult:
    """Run ``search_fn`` ``n_starts`` times with seeds ``base_seed + k`` and
    return the best :class:`AnnealResult`.
    """
    best: AnnealResult | None = None
    for k in range(n_starts):
        r = search_fn(seed=base_seed + k, **kwargs)
        if best is None or r.abs_det > best.abs_det:
            best = r
    assert best is not None
    return best
