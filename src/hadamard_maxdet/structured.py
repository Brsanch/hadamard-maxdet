"""Structured-ansatz constructors and searches.

Restrict the ±1 search space to three well-studied families used by
Rokicki, Orrick, and Brent for record-setting constructions at n >= 20:

  two_circulant
      Order n = 2m, block form ``[[A, B], [B^T, -A^T]]`` with A, B two
      m x m circulants whose first rows (generators) carry all the bits.
      State: 2^(2m) instead of 2^(n^2) = 2^(4m^2).

  bordered_circulant
      Order n, first row ``(1, 1, ..., 1)``, first column
      ``(1, -1, -1, ..., -1)``, and an (n-1) x (n-1) circulant "core".
      State: 2^(n-1).

  skew_circulant
      Order n (odd), a single n x n circulant satisfying A + A^T = 2 I,
      i.e. diagonal = +1 and entry a[i] = -a[n - i] for 1 <= i < n.
      State: 2^((n-1)/2).

All three constructors return a :class:`Matrix` with ±1 entries that
passes :func:`verify`. SA routines flip bits of the generator(s) and
score each proposal via the reference integer determinant (Bareiss).
"""

from __future__ import annotations

import math
import random
import time
from collections.abc import Sequence
from dataclasses import dataclass, field

from hadamard_maxdet.matrix import Matrix
from hadamard_maxdet.search import AnnealResult
from hadamard_maxdet.verifier import integer_determinant


